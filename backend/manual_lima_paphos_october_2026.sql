SELECT
    settings.owner_id,
    concat_ws(
        E'\n\n',
        source_rows.summary,
        'Місце: ' || source_rows.venue,
        'Google Maps: https://www.google.com/maps/search/?api=1&query='
            || replace(source_rows.map_query, ' ', '+'),
        CASE WHEN source_rows.resource_url IS NOT NULL
            THEN source_rows.resource_label || ': ' || source_rows.resource_url END,
        'Джерело: ' || source_rows.source_url
    ),
    'global',
    jsonb_build_array(source_rows.image_url),
    'spirits',
    'public',
    source_rows.latitude,
    source_rows.longitude,
    source_rows.title,
    NULL,
    source_rows.starts_at,
    source_rows.expires_at,
    NULL,
    FALSE
FROM source_rows
CROSS JOIN settings
WHERE NOT EXISTS (
    SELECT 1
    FROM social_events AS existing
    WHERE existing.event_type = 'global'
      AND (
          strpos(existing.description, source_rows.source_url) > 0
          OR (
              existing.starts_at = source_rows.starts_at
              AND existing.location = source_rows.title
              AND existing.image_urls @> jsonb_build_array(source_rows.image_url)
          )
      )
